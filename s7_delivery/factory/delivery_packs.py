"""Delivery pack rendering — layered governed context per team (spec §4–§8).

Level 2 (team pack), Level 3 (story pack) and Level 4 (thin task pack) are
rendered here as pure functions; the engine owns storage, versioning,
provenance and phase transitions. Task packs reference canonical artifacts by
version in `context.json` — they never copy architecture.md.

`AGENTS.md` carries the s7-managed marker line: publication refuses to
overwrite an AGENTS.md that lacks it (someone else's file), and developers
can see at a glance that the file is generated, not hand-written.
"""

