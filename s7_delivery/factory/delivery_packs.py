def pack_id_for(team: str) -> str:
    return f"PACK-{team_slug(team)}"


def branch_name(run_id: str, team: str) -> str:
    """Fresh, disposable context branch — unique per run and team, and never
    a default branch name by construction."""
    return f"s7/{run_id.lower()}-{team_slug(team)}"


# --- Level 3: story pack ----------------------------------------------------


def render_story_pack(story: dict, *, plan_version: int,
                      architecture_version: int) -> dict[str, object]:
    return {
        "story.md": render_agents_md(story),
        "acceptance-criteria.md": render_acceptance_criteria_md(story),
        "dependencies.json": {
            "story_id": story["story_id"],
            "depends_on": story.get("dependencies", []),
        },
        "story-context.json": {
            "story_id": story["story_id"],
            "epic_id": story.get("epic_id", ""),
            "plan_version": plan_version,
            "architecture_version": architecture_version,
            "accountable_team": story.get("accountable_team", ""),
            "repository": story.get("target_repository", ""),
            "acceptance_criteria": [
                ac["ac_id"] for ac in story.get("acceptance_criteria", [])
            ],
        },
    }


# --- Level 4: thin task pack ------------------------------------------------


def render_task_pack(task: dict, story: dict, *, plan_version: int,
                     architecture_version: int,
                     team_pack_version: int) -> dict[str, object]:
    acs = [ac["ac_id"] for ac in story.get("acceptance_criteria", [])]
    task_md = "\n".join([
        f"# {task['task_id']} — {task.get('summary', '')}",
        "",
        f"Story: {task['story_id']} — {story.get('title', '')}",
        f"Accountable team: {task.get('accountable_team', '')}",
        "",
        "## Goal",
        story.get("purpose", ""),
        "",
        "## Acceptance criteria in scope",
        *[f"- {ac_id}" for ac_id in acs],
        "",
        "Canonical context: see `context.json` — architecture and plan are"
        " referenced by version, not copied.",
    ]) + "\n"
    test_plan = "\n".join([
        f"# Test plan — {task['task_id']}",
        "",
        "Every acceptance criterion must have linked executable evidence.",
        "",
        *[f"- [ ] {ac['ac_id']}: covered by a test that fails before the"
          f" change and passes after ({ac['text']})"
          for ac in story.get("acceptance_criteria", [])],
    ]) + "\n"
    return {
        "task.md": task_md,
        "context.json": {
            "task_id": task["task_id"],
            "story_id": task["story_id"],
            "plan_version": plan_version,
            "architecture_version": architecture_version,
            "team_pack_version": team_pack_version,
            "acceptance_criteria": acs,
            "dependencies": task.get("dependencies", []),
        },
        "test-plan.md": test_plan,
        "task-evidence.json": {
            "task_id": task["task_id"],
            "status": task.get("status", "not_started"),
            "commit_ref": task.get("commit_ref", ""),
            "pr_ref": task.get("pr_ref", ""),
            "ci_status": task.get("ci_status", ""),
        },
    }


# --- Level 2: team pack -----------------------------------------------------


def _story_rows(stories: list[dict]) -> tuple[str, str]:
    """(branch_rows, note_rows): the per-story lines the git and database
    standards list — one working branch and one story note per story."""
    branch_rows = "\n".join(
        f"- {s['story_id']}: `feature/{s['story_id'].lower()}-<short-slug>`"
        f" (e.g. `feature/{story_folder_name(s).lower()}`)"
        for s in stories
    )
    note_rows = "\n".join(
        f"- {s['story_id']}: `docs/delivery/{s['story_id']}.md`" for s in stories
    )
    return branch_rows, note_rows


def render_git_workflow_md(
    *, run_id: str, team: str, stories: list[dict],
    default_branch: str = "main",
) -> str:
    """Git rules for the workspace, made concrete: real branch names and
    story ids, the five developer phrases a coding agent acts on, the
    per-criterion loop that plans one criterion into the story note for the
    developer to edit, builds what they left there, and has them observe it
    working before the next is planned, the story-owned-files rule that
    keeps parallel stories from conflicting on merge, and the exact
    "development completed" protocol run before any push. The text is the `git-workflow`
    standard of the run's delivery profile; this renderer supplies the run's
    own names and prepends the s7-managed marker. Published to
    `.s7/shared/git-workflow.md`."""
    branch_rows, note_rows = _story_rows(stories)
    body = layers.standard(
        "git-workflow",
        team=team,
        repository=next((s.get("target_repository", "") for s in stories), ""),
        context_branch=branch_name(run_id, team),
        default_branch=default_branch,
        branch_rows=branch_rows,
        note_rows=note_rows,
        phrase_start=PHRASE_START,
        phrase_plan=PHRASE_PLAN,
        phrase_build=PHRASE_BUILD,
        phrase_commit=PHRASE_COMMIT,
        phrase_push=PHRASE_PUSH,
    )
    return S7_MARKER + "\n" + body + "\n"


def render_db_conventions_md(*, stories: list[dict],
                             default_branch: str = "main") -> str:
    """Schema, migration, config-fragment and seed-data rules — the
    `db-conventions` standard with the run's default branch and story note
    rows. Published to `.s7/shared/db-conventions.md`."""
    _, note_rows = _story_rows(stories)
    body = layers.standard(
        "db-conventions", default_branch=default_branch, note_rows=note_rows,
    )
    return S7_MARKER + "\n" + body + "\n"


# Design tokens — the token *names* are the contract every page reads
# (`var(--ms-red)`); the *values* come from the delivery profile's identity
# file, so a tenant is restyled in one place and the Control Centre's own
# palette (apps/control/web/src/theme.css) stays the default. Pairings marked
# AA are the ones a contrast test should pin.
_PALETTE_TOKENS = (
    ("ink", "--ms-ink"),
    ("muted", "--ms-muted"),
    ("bg", "--ms-bg"),
    ("surface", "--ms-surface"),
    ("surface-2", "--ms-surface-2"),
    ("border", "--ms-border"),
    ("border-strong", "--ms-border-strong"),
    ("primary", "--ms-red"),
    ("primary-dark", "--ms-red-dark"),
    ("primary-pale", "--ms-red-pale"),
    ("success", "--ms-green"),
    ("success-pale", "--ms-green-pale"),
    ("warning-text", "--ms-amber-text"),
    ("warning-pale", "--ms-amber-pale"),
)
_TOKEN_USES = {
    "--ms-ink": "headings, body text on light surfaces (AA on --ms-bg and --ms-surface)",
    "--ms-muted": "help text, secondary labels (AA on --ms-surface)",
    "--ms-bg": "page background",
    "--ms-surface": "cards, form panels",
    "--ms-surface-2": "table stripes, read-only fields",
    "--ms-border": "hairlines, input borders",
    "--ms-border-strong": "focused-but-not-active borders (3:1 on --ms-surface)",
    "--ms-red": "primary action, brand mark, focus ring (AA as text on white)",
    "--ms-red-dark": "primary hover/active, link text",
    "--ms-red-pale": "error banner background (with --ms-red-dark text)",
    "--ms-green": "success text and icons",
    "--ms-green-pale": "success banner background",
    "--ms-amber-text": "warning text",
    "--ms-amber-pale": "warning banner background",
    "--ms-radius-sm": "inputs, buttons",
    "--ms-radius-md": "cards, banners",
    "--ms-space": "spacing unit — use multiples: 8, 16, 24, 32, 48",
    "--ms-font": "one family, system fallback, nothing fetched at runtime",
}


def ui_tokens(identity: dict | None = None) -> list[tuple[str, str, str]]:
    """(token, value, use) rows from the identity file — the active
    profile's unless one is passed."""
    identity = identity if identity is not None else layers.structured("identity")
    try:
        palette = identity["palette"]
        rows = [(tok, palette[key], _TOKEN_USES[tok]) for key, tok in _PALETTE_TOKENS]
        rows += [
            ("--ms-radius-sm", identity["radius"]["sm"], _TOKEN_USES["--ms-radius-sm"]),
            ("--ms-radius-md", identity["radius"]["md"], _TOKEN_USES["--ms-radius-md"]),
            ("--ms-space", identity["space"], _TOKEN_USES["--ms-space"]),
            ("--ms-font", identity["font"], _TOKEN_USES["--ms-font"]),
        ]
    except KeyError as exc:
        raise layers.LayerError(f"identity file is missing {exc.args[0]!r}") from exc
    return rows


# The default profile's tokens — the Control Centre's own palette — resolved
# against the committed identity file explicitly, never an active profile.
UI_TOKENS: tuple[tuple[str, str, str], ...] = tuple(
    ui_tokens(layers.structured("identity", layers.LAYERS_ROOT))
)


def css_tokens(identity: dict | None = None) -> str:
    """The token declarations of the `:root` block, one per line."""
    return "\n".join(f"  {n}: {v};" for n, v, _ in ui_tokens(identity))


def render_ui_guidelines_md(*, team: str, stories: list[dict]) -> str:
    """Developer-facing UI rules for every page a story adds or changes.
    Deterministic and stack-neutral (server-rendered templates or a component
    framework alike); the text is the `ui-guidelines` standard and the tokens
    are the identity file's, so a delivered page reads as the tenant's, not
    as a framework default. Published to `.s7/shared/ui-guidelines.md`."""
    identity = layers.structured("identity")
    tokens = ui_tokens(identity)
    ui_stories = [
        s for s in stories
        if any(k in (s.get("target_component") or "").lower()
               for k in ("ui", "portal", "front", "web", "page"))
    ]
    scope = (
        "Stories in this pack that ship a page: "
        + ", ".join(s["story_id"] for s in ui_stories)
        + "."
        if ui_stories else
        "No story in this pack names a UI component; these rules still bind"
        " any page a story happens to touch."
    )
    body = layers.standard(
        "ui-guidelines",
        team=team,
        scope_line=scope,
        css_block=":root {\n" + css_tokens(identity) + "\n}",
        token_rows="\n".join(f"| `{n}` | `{v}` | {use} |" for n, v, use in tokens),
        organisation=identity["organisation"],
        short_mark=identity["short_mark"],
        product_line=identity["product_line"],
        synthetic_domain=identity["synthetic_domain"],
    )
    return S7_MARKER + "\n" + body + "\n"


def render_code_conventions_md(*, team: str, stories: list[dict],
                               stack: str | None = None) -> str:
    """How the application code itself is written — the gap the UI guidelines
    and DB conventions left open. Deterministic and stack-neutral in its
    rules; only the opening line names the repository's stack, and the first
    rule defers to the repository's own conventions wherever they disagree,
    because S7 has never seen the codebase and the repository has. Published
    to `.s7/shared/code-conventions.md`."""
    stack_line = STACK_LINES.get(stack or "", STACK_LINES[""])
    scope = (
        "Every story in this pack follows it: "
        + ", ".join(s["story_id"] for s in stories) + "."
        if stories else
        "It binds every story published in this pack."
    )
    body = layers.standard(
        "code-conventions",
        team=team,
        stack_line=stack_line,
        scope_line=scope,
    )
    return S7_MARKER + "\n" + body + "\n"


def layout_file_for(stack: str | None) -> str:
    return LAYOUT_BY_STACK.get(stack or "", "ui-layout-thymeleaf")


def render_ui_starter_files(*, stack: str | None = None) -> dict[str, str]:
    """The starter stylesheet and shared page layout a story copies in rather
    than building its own shell: `ui/app.css` from the `ui-starter-css`
    standard with the identity tokens, `ui/layout.html` from the layout
    standard for the repository's stack (Thymeleaf for maven, Jinja2 for
    pytest, Thymeleaf when the stack is unknown). Published under
    `.s7/shared/ui/`."""
    identity = layers.structured("identity")
    names = {
        "organisation": identity["organisation"],
        "short_mark": identity["short_mark"],
        "product_line": identity["product_line"],
    }
    css = layers.standard("ui-starter-css", css_tokens=css_tokens(identity))
    layout = layers.standard(layout_file_for(stack), **names)
    return {
        "ui/app.css": S7_MARKER_CSS + "\n" + css + "\n",
        "ui/layout.html": S7_MARKER + "\n" + layout + "\n",
    }


